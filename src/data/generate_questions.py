# Initialize bank dictionary
bank = {cat: {lvl: [] for lvl in levels} for cat in categories}

# Helper to shuffle options and return them
def make_options(correct_val, distractors):
    opts = [correct_val] + list(distractors)
    random.shuffle(opts)
    return opts

